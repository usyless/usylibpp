    // =========================================================================
    // Isolated Instance Name Validation (UTF-8 & Wide, compile-time & runtime)
    // =========================================================================
    template <typename CharT>
    requires (std::same_as<CharT, char> || std::same_as<CharT, wchar_t>)
    inline constexpr void validate_name(std::basic_string_view<CharT> name) {
        constexpr auto fail = [](const char* msg) {
            throw std::invalid_argument(msg);
        };

        const std::size_t n = name.size();
        if (n == 0) {
            fail("Must provide a non-empty instance name!");
        }
        if (n > 64) {
            fail("Instance name too long!");
        }
        if (name.front() == CharT(' ') || name.back() == CharT(' ')) {
            fail("Instance name cannot start or end with whitespace!");
        }
        if (name.back() == CharT('.')) {
            fail("Instance name cannot end with a dot!");
        }

        constexpr std::basic_string_view<CharT> invalid_chars = [] {
            if constexpr (std::same_as<CharT, wchar_t>) {
                return std::wstring_view{L"/\\:*?|<> \""};
            } else {
                return std::string_view{"/\\:*?|<> \""};
            }
        }();

        for (const CharT c : name) {
            if (static_cast<std::make_unsigned_t<CharT>>(c) < 0x20u) {
                fail("Instance name contains control characters!");
            }
            if (invalid_chars.find(c) != std::basic_string_view<CharT>::npos) {
                fail("Instance name contains invalid path or quote characters!");
            }
        }
    }

    /**
     * Validated non-empty Everything instance name accepted in either Wide
     * (UTF-16) or Narrow (UTF-8) form. String literals are validated at
     * compile time (`consteval`) while dynamic strings are validated at runtime.
     */
    struct InstanceName {
    public:
        template <std::size_t N>
        consteval InstanceName(const wchar_t (&str)[N]) : wide_{str, N - 1}, is_wide_{true} {
            validate_name(wide_);
        }

        template <std::size_t N>
        consteval InstanceName(const char (&str)[N]) : utf8_{str, N - 1}, is_wide_{false} {
            validate_name(utf8_);
        }

        template <WideText T>
        constexpr InstanceName(const T& str) : wide_{str}, is_wide_{true} {
            validate_name(wide_);
        }

        template <Utf8Text T>
        constexpr InstanceName(const T& str) : utf8_{str}, is_wide_{false} {
            validate_name(utf8_);
        }

        [[nodiscard]] constexpr bool is_wide() const noexcept {
            return is_wide_;
        }

        [[nodiscard]] constexpr std::wstring_view get_w_view() const noexcept {
            return wide_;
        }

        [[nodiscard]] constexpr std::string_view get_utf8_view() const noexcept {
            return utf8_;
        }

        [[nodiscard]] inline std::wstring to_wstring() const {
            if (is_wide_) return std::wstring{wide_};
            return detail::to_wide_instance_or_arg(utf8_);
        }

        [[nodiscard]] inline std::string to_utf8() const {
            if (!is_wide_) return std::string{utf8_};
            return detail::to_utf8_instance_or_arg(wide_);
        }

    private:
        std::wstring_view wide_{};
        std::string_view utf8_{};
        bool is_wide_{true};
    };

