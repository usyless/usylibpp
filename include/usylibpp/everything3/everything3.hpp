    inline void SearchOptions::apply_to(SearchState& state) const {
        state.set_match_path(MatchPath)
            .set_match_case(MatchCase)
            .set_match_whole_words(MatchWholeWord)
            .set_match_diacritics(MatchDiacritics)
            .set_match_prefix(MatchPrefix)
            .set_match_suffix(MatchSuffix)
            .set_ignore_punctuation(IgnorePunctuation)
            .set_ignore_whitespace(IgnoreWhitespace)
            .set_regex(Regex)
            .set_folders_first(FoldersFirstMode)
            .set_request_total_size(RequestTotalSize)
            .set_hide_result_omissions(HideResultOmissions)
            .set_sort_mix(SortMix)
            .set_viewport(Offset, Max)
            .clear_sorts()
            .clear_property_requests();

        for (const auto& sort : Sorts) {
            state.add_sort(sort.property_id, sort.ascending);
        }
        for (const auto& prop : Properties) {
            state.add_property_request(prop.property_id, prop.format);
        }
    }

