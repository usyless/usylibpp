    // =========================================================================
    // Query Builder (UTF-8 & Wide versions matching SDK2 Query semantics)
    // =========================================================================
    template <typename CharT>
    requires (std::same_as<CharT, char> || std::same_as<CharT, wchar_t>)
    struct BasicQuery {
        using String = std::basic_string<CharT>;
        using StringView = std::basic_string_view<CharT>;

        String base_dir{};
        String q{};

        constexpr BasicQuery() noexcept = default;

        constexpr explicit BasicQuery(StringView dir) : base_dir{dir} {
            if (!base_dir.ends_with(sep())) base_dir.push_back(sep());

            q += path_prefix();
            q += base_dir;
            q.push_back(quote());
        }

        constexpr BasicQuery& exclude_directory_absolute(StringView dir) {
            if (!q.empty()) q.push_back(space());
            q += excl_path_prefix();
            q += dir;
            if (!dir.ends_with(star()) && !dir.ends_with(sep())) q.push_back(sep());
            q.push_back(quote());
            return *this;
        }

        constexpr BasicQuery& exclude_directory_any(StringView dir) {
            exclude_directory_absolute(strings::concat_strings(base_dir, dir));
            exclude_directory_absolute(strings::concat_strings(base_dir, any_sub_prefix(), dir));
            return *this;
        }

        /**
         * Can't perform any other operations on this query.
         */
        [[nodiscard]] static constexpr BasicQuery from_directory_absolute(StringView dir) {
            BasicQuery query;
            query.base_dir = dir;
            if (!query.base_dir.ends_with(sep())) query.base_dir.push_back(sep());

            query.q = parent_prefix();
            query.q += query.base_dir;
            query.q.push_back(quote());
            return query;
        }

        [[nodiscard]] constexpr const String& get() const & noexcept {
            return q;
        }

        [[nodiscard]] constexpr String&& get() && noexcept {
            return std::move(q);
        }

    private:
        static constexpr CharT sep() noexcept { return CharT('\\'); }
        static constexpr CharT quote() noexcept { return CharT('"'); }
        static constexpr CharT space() noexcept { return CharT(' '); }
        static constexpr CharT star() noexcept { return CharT('*'); }

        static constexpr StringView path_prefix() noexcept {
            if constexpr (std::same_as<CharT, wchar_t>) return L"path:\"";
            else return "path:\"";
        }
        static constexpr StringView excl_path_prefix() noexcept {
            if constexpr (std::same_as<CharT, wchar_t>) return L"!path:\"";
            else return "!path:\"";
        }
        static constexpr StringView any_sub_prefix() noexcept {
            if constexpr (std::same_as<CharT, wchar_t>) return L"*\\";
            else return "*\\";
        }
        static constexpr StringView parent_prefix() noexcept {
            if constexpr (std::same_as<CharT, wchar_t>) return L"parent:\"";
            else return "parent:\"";
        }
    };

